def main():
    data_dir = ROOT / 'data'
    train = []
    for category in CATEGORIES:
        lines = PAIRS[category].splitlines()
        assert len(lines) == 10
        for line in lines:
            prompt, normal, style = line.split('|')
            train.append(dict(id=f'train{len(train)+1:03d}', category=category,
                              prompt=prompt, normal=normal, style=style))
    outputs = {'train_pairs.json': train}
    for name, source, prefix in [('validation.json', VALIDATION, 'val'),
                                 ('generalization.json', GENERALIZATION, 'gen')]:
        lines = source.splitlines()
        assert len(lines) == 50
        outputs[name] = [dict(id=f'{prefix}{i+1:03d}', category=CATEGORIES[i // 5], prompt=p)
                         for i, p in enumerate(lines)]
    original = json.loads((data_dir / 'questions.json').read_text(encoding='utf-8'))
    all_rows = original + [r for rows in outputs.values() for r in rows]
    assert len({r['prompt'] for r in all_rows}) == len(all_rows), 'Duplicate prompt'
    assert len({r['id'] for r in all_rows}) == len(all_rows), 'Duplicate id'
    manifest = {'source': 'Manually authored by Codex; no generated model outputs reused.',
                'existing_questions_used_for_editing': False, 'text_hash_policy': 'UTF-8 with LF line endings', 'splits': {}}
    for name, rows in outputs.items():
        assert len(set(Counter(r['category'] for r in rows).values())) == 1
        payload = json.dumps(rows, ensure_ascii=False, indent=2) + '\n'
        (data_dir / name).write_text(payload, encoding='utf-8', newline='\n')
        manifest['splits'][name] = dict(count=len(rows), categories=dict(Counter(r['category'] for r in rows)),
                                       sha256=hashlib.sha256(payload.encode()).hexdigest())
    manifest['original_questions_sha256'] = hashlib.sha256((data_dir / 'questions.json').read_bytes().replace(b'\r\n',b'\n')).hexdigest()
    (data_dir / 'edit_data_manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    print(json.dumps({k: len(v) for k, v in outputs.items()}))


if __name__ == '__main__':
    main()
