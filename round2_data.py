def main():
    dest=ROOT/'data/round2'; dest.mkdir(exist_ok=True)
    rows=[dict(id=f'r2train{i:02}',category=c,prompt=q,normal=n,style=s) for i,(c,q,n,s) in enumerate(PAIRS)]
    all_questions=[r['prompt'] for r in rows]
    dump(dest/'train.json',rows)
    for name,groups in [('validation',VALIDATION),('test',TEST)]:
        rows=[dict(id=f'r2{name}{i*len(g)+j:02}',category=c,prompt=q) for i,(c,g) in enumerate(zip(['daily','knowledge','explanation','advice'],groups)) for j,q in enumerate(g)]
        all_questions.extend(r['prompt'] for r in rows); dump(dest/f'{name}.json',rows)
    assert len(all_questions)==len(set(all_questions))==96
    old={r['prompt'] for split in ['train','validation','test'] for r in dataset(split)}
    assert not old.intersection(all_questions)
    # Same side probes: previously inspected, descriptive regression tests only.
    dump(dest/'side.json',dataset('side'))
    files=list(dest.glob('*.json'))+[ROOT/'ROUND2_PROTOCOL.md']
    dump(dest/'manifest.json',{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes().replace(b'\r\n',b'\n')).hexdigest() for p in files})

if __name__=='__main__': main()
